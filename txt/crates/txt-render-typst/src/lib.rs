//! Typst print backend for txt (ADR 0001): translates the semantic `.tx`
//! document model into Typst source. Authors never see Typst; no Typst
//! concept may leak into `.tx`. The design layer lives in `template.typ`
//! (in production, a versioned design-spec dependency).

pub mod math;

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};
use txt_core::{directive_fields, structure, Block, BlockSchema, BodyElement, Document, Inline, Node};

pub const TEMPLATE_TYP: &str = include_str!("template.typ");

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Audience {
    Student,
    Teacher,
}

impl Audience {
    pub fn as_str(self) -> &'static str {
        match self {
            Audience::Student => "student",
            Audience::Teacher => "teacher",
        }
    }
}

pub struct BookMeta {
    pub title: String,
    pub subtitle: Option<String>,
    pub edition: String,
}

/// A file the build directory must contain (figure images, etc.).
pub struct Asset {
    pub source: PathBuf,
    /// Destination path relative to the build directory.
    pub dest: String,
}

pub struct RenderedBook {
    pub main_typ: String,
    pub assets: Vec<Asset>,
}

#[derive(Debug)]
pub struct RenderError {
    pub file: PathBuf,
    pub message: String,
}

impl std::fmt::Display for RenderError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{}: {}", self.file.display(), self.message)
    }
}

impl std::error::Error for RenderError {}

struct Ctx<'a> {
    audience: Audience,
    labels: &'a BTreeMap<String, String>,
    assets: Vec<Asset>,
    file: PathBuf,
    base: PathBuf,
}

pub fn render_book(
    meta: &BookMeta,
    files: &[(PathBuf, Document)],
    audience: Audience,
) -> Result<RenderedBook, RenderError> {
    let labels = build_labels(files);
    let mut ctx = Ctx {
        audience,
        labels: &labels,
        assets: Vec::new(),
        file: PathBuf::new(),
        base: PathBuf::new(),
    };

    let mut out = String::new();
    out.push_str("// Generated by txt — do not edit. Edit the .tx sources instead.\n");
    out.push_str("#import \"template.typ\": *\n");
    out.push_str(&format!(
        "#show: book.with(title: \"{}\", {}edition: \"{}\", audience: \"{}\")\n\n",
        esc_string(&meta.title),
        match &meta.subtitle {
            Some(s) => format!("subtitle: \"{}\", ", esc_string(s)),
            None => String::new(),
        },
        esc_string(&meta.edition),
        audience.as_str(),
    ));

    for (path, doc) in files {
        if doc.frontmatter.kind == "summary" {
            continue; // the spine orders files; it renders no content
        }
        ctx.file = path.clone();
        ctx.base = path.parent().unwrap_or(Path::new(".")).to_path_buf();
        let marker = if doc.frontmatter.kind == "chapter" { "=" } else { "==" };
        out.push_str(&format!("{marker} {}\n\n", esc_markup(&doc.frontmatter.title)));
        render_nodes(&mut ctx, &doc.nodes, &mut out)?;
    }

    Ok(RenderedBook { main_typ: out, assets: ctx.assets })
}

/// Human labels for referenceable ids: numbered per kind in book order
/// ("Figure 1", "Example 3"); file ids resolve to their titles.
fn build_labels(files: &[(PathBuf, Document)]) -> BTreeMap<String, String> {
    let mut labels = BTreeMap::new();
    let mut counters: BTreeMap<&'static str, usize> = BTreeMap::new();
    for (_, doc) in files {
        labels.insert(doc.frontmatter.id.clone(), doc.frontmatter.title.clone());
        for b in doc.blocks() {
            let Some(id) = &b.id else { continue };
            let pretty = match b.kind.as_str() {
                "figure" => "Figure",
                "example" => "Example",
                "exercise" => "Exercise",
                "definition" => "Definition",
                "theorem" => "Theorem",
                "table" => "Table",
                _ => {
                    labels.insert(id.clone(), format!("“{id}”"));
                    continue;
                }
            };
            let n = counters.entry(pretty).or_insert(0);
            *n += 1;
            labels.insert(id.clone(), format!("{pretty} {n}"));
        }
    }
    labels
}

fn render_nodes(ctx: &mut Ctx, nodes: &[Node], out: &mut String) -> Result<(), RenderError> {
    for node in nodes {
        match node {
            Node::Text(t) => render_text(ctx, &t.content, out)?,
            Node::Block(b) => render_block(ctx, b, out)?,
        }
    }
    Ok(())
}

fn render_text(ctx: &Ctx, content: &str, out: &mut String) -> Result<(), RenderError> {
    for el in structure(content) {
        match el {
            BodyElement::Heading { level, content } => {
                let marker = "=".repeat(level as usize);
                out.push_str(&format!("{marker} {}\n\n", inlines(ctx, &content)?));
            }
            BodyElement::Paragraph(items) => {
                out.push_str(&inlines(ctx, &items)?);
                out.push_str("\n\n");
            }
            BodyElement::BulletList(list) => {
                for item in &list {
                    out.push_str(&format!("- {}\n", inlines(ctx, item)?));
                }
                out.push('\n');
            }
            BodyElement::OrderedList(list) => {
                for item in &list {
                    out.push_str(&format!("+ {}\n", inlines(ctx, item)?));
                }
                out.push('\n');
            }
            BodyElement::DisplayMath(src) => {
                let m = math::tex_to_typst(&src).map_err(|e| err(ctx, &src, e))?;
                out.push_str(&format!("$ {m} $\n\n"));
            }
        }
    }
    Ok(())
}

fn render_block(ctx: &mut Ctx, b: &Block, out: &mut String) -> Result<(), RenderError> {
    if ctx.audience == Audience::Student
        && b.attrs.get("audience").map(String::as_str) == Some("teacher")
    {
        return Ok(());
    }

    let label = b.id.as_ref().and_then(|id| ctx.labels.get(id).cloned());

    match b.kind.as_str() {
        "objective" => wrap(ctx, b, "#tx-objective", &[], out)?,
        "definition" => {
            let mut l = label.unwrap_or_else(|| "Definition".into());
            if let Some(term) = b.attrs.get("term") {
                l = format!("{l} — {term}");
            }
            wrap(ctx, b, "#tx-definition", &[("label", Arg::Str(l))], out)?;
        }
        "theorem" => {
            let mut l = label.unwrap_or_else(|| "Theorem".into());
            if let Some(name) = b.attrs.get("name") {
                l = format!("{l} — {name}");
            }
            wrap(ctx, b, "#tx-theorem", &[("label", Arg::Str(l))], out)?;
        }
        "example" => {
            let l = label.unwrap_or_else(|| "Example".into());
            wrap(ctx, b, "#tx-example", &[("label", Arg::Str(l))], out)?;
        }
        "exercise" => {
            let mut l = label.unwrap_or_else(|| "Exercise".into());
            if let Some(d) = b.attrs.get("difficulty").and_then(|d| d.parse::<usize>().ok()) {
                l = format!("{l} · {}", "●".repeat(d));
            }
            wrap(ctx, b, "#tx-exercise", &[("label", Arg::Str(l))], out)?;
        }
        "solution" => wrap(ctx, b, "#tx-solution", &[], out)?,
        "answer" => wrap(ctx, b, "#tx-answer", &[], out)?,
        "hint" => wrap(ctx, b, "#tx-hint", &[], out)?,
        "note" => wrap(ctx, b, "#tx-note", &[], out)?,
        "warning" => wrap(ctx, b, "#tx-warning", &[], out)?,
        "activity" => wrap(ctx, b, "#tx-activity", &[], out)?,
        "vocabulary" => wrap(ctx, b, "#tx-vocabulary", &[], out)?,
        "summary" => wrap(ctx, b, "#tx-summary", &[], out)?,
        "figure" => render_figure(ctx, b, label.as_deref(), out)?,
        // citation/source records render nothing in the page flow (v0)
        "citation" | "source" => {}
        _ => render_nodes(ctx, &b.children, out)?,
    }
    Ok(())
}

enum Arg {
    Str(String),
}

fn wrap(
    ctx: &mut Ctx,
    b: &Block,
    func: &str,
    args: &[(&str, Arg)],
    out: &mut String,
) -> Result<(), RenderError> {
    let mut body = String::new();
    render_nodes(ctx, &b.children, &mut body)?;
    let rendered_args = args
        .iter()
        .map(|(k, Arg::Str(v))| format!("{k}: \"{}\"", esc_string(v)))
        .collect::<Vec<_>>()
        .join(", ");
    if rendered_args.is_empty() {
        out.push_str(&format!("{func}[\n{}]\n\n", body.trim_end().to_string() + "\n"));
    } else {
        out.push_str(&format!(
            "{func}({rendered_args})[\n{}]\n\n",
            body.trim_end().to_string() + "\n"
        ));
    }
    Ok(())
}

fn render_figure(
    ctx: &mut Ctx,
    b: &Block,
    label: Option<&str>,
    out: &mut String,
) -> Result<(), RenderError> {
    let schema_fields = &BlockSchema::v1().kind("figure").expect("figure in schema").fields;
    let fields = directive_fields(b, schema_fields);
    let src = b
        .attrs
        .get("src")
        .ok_or_else(|| err(ctx, "figure", "missing src (check should have caught this)".into()))?;
    let source = ctx.base.join(src);
    let filename = source
        .file_name()
        .map(|f| f.to_string_lossy().into_owned())
        .unwrap_or_else(|| "figure".into());
    let dest = format!("assets/fig-{:02}-{}", ctx.assets.len() + 1, filename);
    ctx.assets.push(Asset { source, dest: dest.clone() });

    let alt = fields.get("alt").cloned().unwrap_or_default();
    let caption = fields.get("caption").cloned().unwrap_or_default();
    let credit = match fields.get("credit") {
        Some(c) => format!("[{}]", esc_markup(c)),
        None => "none".into(),
    };
    out.push_str(&format!(
        "#tx-figure(path: \"{}\", alt: \"{}\", caption: [{}], credit: {}, label: \"{}\")\n\n",
        esc_string(&dest),
        esc_string(&alt),
        esc_markup(&caption),
        credit,
        esc_string(label.unwrap_or("Figure")),
    ));
    Ok(())
}

fn inlines(ctx: &Ctx, items: &[Inline]) -> Result<String, RenderError> {
    let mut out = String::new();
    for item in items {
        match item {
            Inline::Str(s) => out.push_str(&esc_markup(s)),
            Inline::Strong(inner) => out.push_str(&format!("*{}*", inlines(ctx, inner)?)),
            Inline::Emph(inner) => out.push_str(&format!("_{}_", inlines(ctx, inner)?)),
            Inline::Code(c) => out.push_str(&format!("`{c}`")),
            Inline::Math(m) => {
                let converted = math::tex_to_typst(m).map_err(|e| err(ctx, m, e))?;
                out.push_str(&format!("${converted}$"));
            }
            Inline::Ref(id) => match ctx.labels.get(id) {
                Some(l) => out.push_str(&esc_markup(l)),
                None => return Err(err(ctx, id, format!("unresolved reference `@{id}`"))),
            },
            Inline::Citation(key) => out.push_str(&esc_markup(&format!("[{key}]"))),
            Inline::Gloss(term) => out.push_str(&format!("_{}_", esc_markup(term))),
        }
    }
    Ok(out)
}

fn err(ctx: &Ctx, context: &str, message: String) -> RenderError {
    RenderError {
        file: ctx.file.clone(),
        message: format!("{message} (in `{context}`)"),
    }
}

/// Escapes Typst markup-mode specials so `.tx` prose stays prose.
fn esc_markup(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        if matches!(c, '\\' | '#' | '$' | '[' | ']' | '*' | '_' | '`' | '@' | '<' | '>' | '~') {
            out.push('\\');
        }
        out.push(c);
    }
    out
}

/// Escapes Typst string-literal specials.
fn esc_string(s: &str) -> String {
    s.replace('\\', "\\\\").replace('"', "\\\"")
}

#[cfg(test)]
mod tests {
    use super::*;
    use txt_core::parse;

    fn render(body: &str, audience: Audience) -> String {
        let src = format!(
            "+++\nid = \"ch-t\"\nkind = \"chapter\"\ntitle = \"Test chapter\"\n+++\n{body}"
        );
        let doc = parse(&src).unwrap();
        let meta = BookMeta {
            title: "Test Book".into(),
            subtitle: None,
            edition: "0.0".into(),
        };
        render_book(&meta, &[(PathBuf::from("t.tx"), doc)], audience)
            .unwrap()
            .main_typ
    }

    #[test]
    fn teacher_blocks_stripped_from_student_build() {
        let body = "::: exercise {#e1}\nSolve $x + 1 = 2$.\n\n::: answer {audience=\"teacher\"}\n$x = 1$.\n:::\n:::\n";
        let student = render(body, Audience::Student);
        assert!(!student.contains("tx-answer"), "{student}");
        let teacher = render(body, Audience::Teacher);
        assert!(teacher.contains("tx-answer"), "{teacher}");
    }

    #[test]
    fn refs_resolve_to_numbered_labels() {
        let body = "::: example {#ex-a}\nFirst.\n:::\n\n::: example {#ex-b}\nSee @ex-a.\n:::\n";
        let out = render(body, Audience::Student);
        assert!(out.contains("label: \"Example 1\""), "{out}");
        assert!(out.contains("See Example 1."), "{out}");
    }

    #[test]
    fn math_and_escaping() {
        let out = render("Solve $3x = 6$ for #1 _test_.\n", Audience::Student);
        assert!(out.contains("$3 x = 6$"), "{out}");
        assert!(out.contains("\\#1 \\_test\\_"), "{out}");
    }

    #[test]
    fn figure_becomes_asset() {
        let body = "::: figure {#f-1 src=\"figs/x.svg\"}\nalt: Alt text.\ncaption: Cap.\n:::\n";
        let src = format!(
            "+++\nid = \"ch-t\"\nkind = \"chapter\"\ntitle = \"T\"\n+++\n{body}"
        );
        let doc = parse(&src).unwrap();
        let meta = BookMeta { title: "B".into(), subtitle: None, edition: "0".into() };
        let rendered = render_book(
            &meta,
            &[(PathBuf::from("dir/t.tx"), doc)],
            Audience::Student,
        )
        .unwrap();
        assert_eq!(rendered.assets.len(), 1);
        assert_eq!(rendered.assets[0].source, PathBuf::from("dir/figs/x.svg"));
        assert!(rendered.main_typ.contains("assets/fig-01-x.svg"));
        assert!(rendered.main_typ.contains("alt: \"Alt text.\""));
    }
}
